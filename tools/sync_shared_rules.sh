#!/usr/bin/env bash
# Copies the pure-Kotlin rule files from the server (single source of truth) into the Android app,
# rewriting only the package line. Run after editing anything in server_app/src/main/kotlin/domain/.
#   Server  : package domain
#   Android : package com.google.mytaskmanager.domain.rules
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/server_app/src/main/kotlin/domain"
DST="$ROOT/android_app/app/src/main/java/com/google/mytaskmanager/domain/rules"
mkdir -p "$DST"
for f in "$SRC"/*.kt; do
  { echo "// GENERATED by tools/sync_shared_rules.sh from server_app/src/main/kotlin/domain/$(basename "$f") - do not edit here."
    sed 's/^package domain$/package com.google.mytaskmanager.domain.rules/' "$f"; } > "$DST/$(basename "$f")"
done
# the matching unit test
TDST="$ROOT/android_app/app/src/test/java/com/google/mytaskmanager/domain/rules"
mkdir -p "$TDST"
sed -e 's/^package domain$/package com.google.mytaskmanager.domain.rules/' \
    -e 's/^import kotlin.test.*$/&/' "$ROOT/server_app/src/test/kotlin/domain/DomainRulesTest.kt" > "$TDST/DomainRulesTest.kt"
echo "Synced $(ls "$DST" | wc -l) rule files to the Android app."
